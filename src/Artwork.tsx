export function MotifArt({
  id,
  color,
  thumbnail = false,
  mode = "painted",
}: {
  id: string;
  color: string;
  thumbnail?: boolean;
  mode?: string;
}) {
  const motif = MOTIFS.find((m) => m.id === id);
  if (!motif) return null;
  if (id.startsWith("original:"))
    return (
      <div className="original-art-thumb">
        <div>
          <ClassicMotif id={id} design={INITIAL} />
        </div>
      </div>
    );
  const path = {
    center: centerPaths,
    side: sidePaths,
    sky: skyPaths,
    bottom: bottomPaths,
  }[motif.category][motif.shape];
  if (thumbnail)
    return (
      <svg
        viewBox="-5 -5 110 110"
        aria-hidden="true"
        fill="none"
        stroke={color}
        strokeWidth="1.5"
      >
        <path
          d={path}
          fill={mode === "line" ? "none" : color}
          fillOpacity={mode === "line" ? 0 : 0.16}
        />
      </svg>
    );
  const transforms = {
    center: "translate(670 105) scale(2.25)",
    side: "translate(35 115) scale(1.1 1.8)",
    sky: "translate(590 20) scale(1.6 .7)",
    bottom: "translate(0 325) scale(10 1)",
  };
  return (
    <svg
      viewBox="0 0 1000 426"
      className="motif-art"
      aria-hidden="true"
      fill="none"
      style={{
        filter:
          mode === "luminous"
            ? `drop-shadow(0 0 4px ${color})`
            : mode === "painted"
              ? "drop-shadow(0 5px 4px #0004)"
              : undefined,
      }}
      stroke={color}
      strokeWidth={motif.category === "bottom" ? 0.55 : 1.2}
      strokeLinecap="round"
      strokeLinejoin="round"
    >
      <g transform={transforms[motif.category]}>
        <path
          d={path}
          fill={mode === "line" ? "none" : color}
          fillOpacity={mode === "line" ? 0 : 0.16}
        />
      </g>
      {motif.category === "side" && (
        <g transform="translate(965 115) scale(-1.1 1.8)">
          <path
            d={path}
            fill={mode === "line" ? "none" : color}
            fillOpacity={mode === "line" ? 0 : 0.16}
          />
        </g>
      )}
    </svg>
  );
}
